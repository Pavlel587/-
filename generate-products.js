// этот скрипт создаёт большой каталог для опытов
const fs = require('fs');

const COUNT = 5000;
const names = ['Огурец', 'Обои', 'Рынок', 'Лампа', 'Чебурек', 'Полка', 'Якутия', 'Стул', 'Коврик',
  'Ваза', 'Зеркало', 'Корзина', 'Часы', 'Подушка', 'Пуф', 'Люстра', 'Кот', 'Монитор',
  'Компьютерная мышь', 'Гараж', 'Уфа', 'Скрепки', 'Мультитул', 'Чебурек', 'Торт', 'Ускоритель частиц',
  'Машина времени', 'Уголь', 'Кофеварка', 'Плавильня'];

const products = [];

for (let i = 1; i <= COUNT; i++) {
  products.push({
    id: i,
    name: names[i % names.length] + ' № ' + i,
    price: 1000 + i * 6,
    img: 'img/' + (i % 14 + 1) + '.jpg'
  });
}

fs.writeFileSync('products.json', JSON.stringify(products, null, 2));
console.log('Создан каталог из ' + COUNT + ' товаров');
